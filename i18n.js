const LANG_KEY = 'organizeit.lang';
let lang = 'ar';
try { if (I18N[localStorage.getItem(LANG_KEY)]) lang = localStorage.getItem(LANG_KEY); } catch (e) {}

function t(key, params) {
  let s = I18N[lang][key] ?? I18N.ar[key] ?? key;
  if (params && typeof s === 'string') {
    s = s.replace(/\{(\w+)\}/g, (m, k) => (k in params ? params[k] : m));
  }
  return s;
}
// اسم بديل للاستخدام جوه الدوال اللي فيها متغير اسمه t (المهمة)
const tr = t;

// النصوص الثابتة في الـ HTML: data-i18n / data-i18n-title / data-i18n-placeholder
function applyStaticText() {
  const root = document.documentElement;
  root.lang = lang;
  root.dir = t('dir');
  document.title = t('appTitle');
  document.querySelectorAll('[data-i18n]').forEach(e => { e.textContent = t(e.dataset.i18n); });
  document.querySelectorAll('[data-i18n-title]').forEach(e => { e.title = t(e.dataset.i18nTitle); });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(e => { e.placeholder = t(e.dataset.i18nPlaceholder); });
}
